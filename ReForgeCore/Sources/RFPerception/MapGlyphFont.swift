/// 地図に使う同梱フォント(BIZ UD ゴシック)に字が無いとき、同じ役目の字に替える表。
/// 地図は 1 マス 1 字を固定の書体で描くので、書体に無い字は字が無い四角(豆腐)になる。
/// 内容の glyph は書体にある字にするのが本来で(照合する試験が失敗で知らせる)、
/// この表は、まだ直っていない内容・後から足された内容でも豆腐を出さないための受け皿。
public enum MapGlyphFont {
    /// 書体に無い字 → 書体にある代わりの字。右はどれも同梱フォントにある字で、置き換えで別の物が同じ字にならない(どちらも試験で確かめる)。
    /// 置き換え先の選び方(game-designer): 夜の目 ◉ ・水の ≈ ・既にある字と見分けがつく字にする。
    public static let substitutes: [Character: Character] = [
        "\u{25A5}": "\u{25C6}", // U+25A5 → ◆
        "\u{25A3}": "\u{25C7}", // U+25A3 → ◇
        "\u{25A4}": "\u{25A1}", // U+25A4 → □
        "\u{25CC}": "\u{25E6}", // U+25CC → ◦
        "\u{273F}": "\u{2756}", // U+273F → ❖
        "\u{25EC}": "\u{25B3}", // U+25EC → △
        "\u{2592}": "\u{25A0}", // U+2592 → ■
        "\u{2219}": "\u{00B7}", // U+2219 → ·
        "\u{2302}": "\u{25CB}", // U+2302 → ○
        "\u{234B}": "\u{25B2}", // U+234B → ▲
        "\u{2237}": "\u{2261}", // U+2237 → ≡
    ]

    /// 地図に描く字列を、書体にある字だけにする(表に無い字はそのまま)。
    public static func safe(_ glyph: String) -> String {
        guard glyph.contains(where: { substitutes[$0] != nil }) else { return glyph }
        return String(glyph.map { substitutes[$0] ?? $0 })
    }
}
